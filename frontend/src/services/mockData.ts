export const generate30DayTelemetry = (rec?: Recommendation): TelemetryPoint[] => {
  const points: TelemetryPoint[] = [];
  const now = new Date();
  const targetMeanCpu = rec?.mean_cpu ?? 16;
  const targetMeanRam = rec?.mean_ram ?? 32;

  // 30 days of data, 1 point per 6 hours (120 points) for fast smooth charting
  for (let i = 120; i >= 0; i--) {
    const time = new Date(now.getTime() - i * 6 * 60 * 60 * 1000);
    const hour = time.getHours();
    const dayOfWeek = time.getDay();
    const isWeekend = dayOfWeek === 0 || dayOfWeek === 6;

    // Diurnal day-night curve
    const diurnalFactor = Math.sin(((hour - 9) / 24) * 2 * Math.PI) * 0.4 + 1;
    const weekendFactor = isWeekend && rec?.environment === 'dev' ? 0.25 : 1;
    const noiseCpu = (Math.sin(i * 1.3) + Math.cos(i * 0.7)) * 4;
    const noiseRam = (Math.sin(i * 0.8)) * 3;

    const cpuVal = Math.max(2, Math.min(96, +(targetMeanCpu * diurnalFactor * weekendFactor + noiseCpu).toFixed(1)));
    const ramVal = Math.max(8, Math.min(95, +(targetMeanRam * (diurnalFactor * 0.3 + 0.7) + noiseRam).toFixed(1)));

    points.push({
      timestamp: time.toISOString(),
      date: time.toLocaleDateString('en-IN', { month: 'short', day: 'numeric' }),
      time: time.toLocaleTimeString('en-IN', { hour: '2-digit', minute: '2-digit' }),
      cpu_percent: cpuVal,
      ram_percent: ramVal,
      disk_iops: Math.round(cpuVal * 18 + 120),
      network_mbps: +(cpuVal * 1.4 + 15).toFixed(1),
    });
  }

  return points;
};
